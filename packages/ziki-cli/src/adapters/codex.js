import path from "node:path";
import { ZIKI_MCP_TOOL_ALLOWLIST, ZIKI_MCP_TOOL_DENYLIST } from "../allowlist.js";

// EXPERIMENTAL, not live-verified: no Codex binary was available to test
// against. Config format per the official Codex config reference
// (~/.codex/config.toml, [mcp_servers.<id>] tables, enabled_tools /
// disabled_tools). One assumption is unverified and flagged below: the exact
// identifier Codex uses for MCP tools in those lists.

export const CODEX_MCP_SERVER_NAME = "ziki";
export const CODEX_CONFIG_NAME = "config.toml";

export const MANAGED_BEGIN = "# >>> ziki-cli managed: codex adapter (experimental) >>>";
export const MANAGED_END = "# <<< ziki-cli managed: codex adapter <<<";

export function CODEX_CONFIG_DIR(home) {
  return path.join(home, ".codex");
}

export function CODEX_CONFIG_PATH(home) {
  return path.join(CODEX_CONFIG_DIR(home), CODEX_CONFIG_NAME);
}

// shortcut: MCP tool identifiers are assumed to be the plain wire names
// (ziki_get_work). If a live Codex run shows a server prefix or another
// shape, change this one function; upgrade when verified.
export function codexToolId(mcpToolName) {
  return mcpToolName;
}

function tomlString(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function tomlList(items) {
  return `[${items.map(tomlString).join(", ")}]`;
}

export function buildCodexBlock({ serverPath, serverUrl }) {
  const deniedTools = ZIKI_MCP_TOOL_DENYLIST;
  const lines = [
    MANAGED_BEGIN,
    "# Generated by `ziki-cli setup-codex`. Edit outside the markers freely;",
    "# re-running setup replaces everything between them. Backed up before writes.",
    "# Experimental: restriction identifiers not yet verified against a live Codex.",
    `[mcp_servers.${CODEX_MCP_SERVER_NAME}]`,
    `command = ${tomlString("node")}`,
    `args = ${tomlList([serverPath])}`,
    `env = { ZIKI_URL = ${tomlString(serverUrl)} }`,
    `enabled_tools = ${tomlList(ZIKI_MCP_TOOL_ALLOWLIST.map(codexToolId))}`,
    `disabled_tools = ${tomlList(deniedTools.map(codexToolId))}`,
    MANAGED_END,
  ];
  return `${lines.join("\n")}\n`;
}

// Insert or replace the managed block. Anything outside the markers is
// untouched. A foreign [mcp_servers.ziki] table outside the markers is a
// conflict for the human, never a silent second definition.
export function upsertManagedBlock(existingText, block) {
  const text = existingText ?? "";
  const begin = text.indexOf(MANAGED_BEGIN);
  const end = text.indexOf(MANAGED_END);
  if (begin !== -1 && end !== -1 && end > begin) {
    return text.slice(0, begin) + block + text.slice(end + MANAGED_END.length).replace(/^\n/, "");
  }
  if (begin !== -1 || end !== -1) {
    throw new Error("config.toml has a half-written ziki block; remove the markers by hand first");
  }
  if (/(^|\n)\s*\[mcp_servers\.ziki\]/.test(text)) {
    throw new Error('config.toml already defines [mcp_servers.ziki] outside the managed block; remove it by hand first');
  }
  const sep = text === "" || text.endsWith("\n") ? "" : "\n";
  const gap = text === "" ? "" : "\n";
  return `${text}${sep}${gap}${block}`;
}
